// Parses docs/ATTACKS.md (written by scripts/attack_gallery.py from a live run)
// into data for the attack gallery page. The page shows only what the report says.

const LINK = /\[([a-z_ ]+) [^\]]*\]\((https:\/\/testnet\.nearblocks\.io\/txns\/(\w+))\)/g;

export function parseAttacks(md) {
  const head = md.match(/Generated by `scripts\/attack_gallery\.py` on (.+?) against `([^`]+)`/);
  const score = md.match(/\*\*(\d+) of (\d+) outcomes matched/);
  const rows = [];
  for (const line of md.split("\n")) {
    if (!/^\| \d+ \|/.test(line)) continue;
    const cells = line.split("|").slice(1, -1).map((c) => c.trim());
    if (cells.length < 8) continue;
    const [n, title, job, layer, expected, actual, mark, txcell] = cells;
    const txs = [...txcell.matchAll(LINK)].map((m) => ({ label: m[1], url: m[2], hash: m[3] }));
    rows.push({ n: Number(n), title, job: job === "—" ? null : Number(job), layer, expected, actual, ok: mark.includes("✅"), txs });
  }
  const money = {};
  for (const [k, re] of Object.entries({
    escrowed: /Escrowed in the attack jobs: ([\d.]+) NEAR/, refunded: /Refunded to the owner's budget: ([\d.]+) NEAR/,
    paid: /Paid to the cheating provider: \*\*([\d.]+) NEAR/, kept: /difference ([\d.]+) NEAR/, gas: /verdict transactions: ([\d.]+) NEAR/,
  })) {
    const m = md.match(re);
    if (m) money[k] = m[1];
  }
  return {
    generatedAt: head ? head[1] : null, contractId: head ? head[2] : null,
    matched: score ? Number(score[1]) : rows.filter((r) => r.ok).length,
    total: score ? Number(score[2]) : rows.length, rows, money,
  };
}
